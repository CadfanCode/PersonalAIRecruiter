-- A submitted application, frozen at the moment the user confirmed it: the ad as it was, and the exact CV and letter (their
-- content and PDF bytes) that were sent. Later regenerations, chat edits and undo never touch this row. job_id goes NULL if
-- the job itself is ever deleted; the snapshot stays.
CREATE TABLE submitted_application (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id              BIGINT UNIQUE REFERENCES job (id) ON DELETE SET NULL,
    title               TEXT NOT NULL,
    employer            TEXT,
    municipality        TEXT,
    url                 TEXT,
    apply_url           TEXT,
    language            TEXT,
    ad_text             TEXT,
    search_mode         TEXT,
    role_type           TEXT,
    score_total         INT,
    submitted_at        TIMESTAMPTZ NOT NULL,
    cv_version          INT,
    cv_file             TEXT,
    cv_content_json     JSONB,
    cv_pdf              BYTEA,
    letter_version      INT,
    letter_file         TEXT,
    letter_content_json JSONB,
    letter_pdf          BYTEA
);
CREATE INDEX idx_submitted_application_at ON submitted_application (submitted_at DESC);

-- Which employer portals the user chose to save a login for. Host and username only: the password is in the OS credential
-- store, under an account named after the host.
CREATE TABLE saved_login (
    host         TEXT PRIMARY KEY,
    username     TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ
);
