-- JobPilot initial schema (SPEC section 4, plus claude_call from SPEC 5.1).
-- Settings and answers-memory tables are added by the milestones that use them.

CREATE TABLE profile (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      TEXT NOT NULL,
    headline       TEXT,
    email          TEXT,
    phone          TEXT,
    city           TEXT,
    website        TEXT,
    github         TEXT,
    linkedin       TEXT,
    languages_json JSONB NOT NULL DEFAULT '[]',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cv_entry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         TEXT NOT NULL CHECK (kind IN ('EDUCATION', 'WORK', 'INTERNSHIP', 'PROJECT', 'OWN_BUSINESS',
                                               'VOLUNTEER', 'CERTIFICATION', 'AWARD', 'PUBLICATION',
                                               'CONFERENCE', 'LANGUAGE', 'OTHER')),
    title        TEXT NOT NULL,
    organisation TEXT,
    location     TEXT,
    start_ym     VARCHAR(7),
    end_ym       VARCHAR(7),
    ongoing      BOOLEAN NOT NULL DEFAULT FALSE,
    summary      TEXT,
    sort_order   INT NOT NULL DEFAULT 0,
    hidden       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE cv_fact (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id   BIGINT NOT NULL REFERENCES cv_entry (id) ON DELETE CASCADE,
    text_en    TEXT,
    text_sv    TEXT,
    evidence   TEXT,
    metrics    TEXT,
    sort_order INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_cv_fact_entry ON cv_fact (entry_id);

CREATE TABLE skill (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    category     TEXT,
    level        TEXT,
    years        NUMERIC(4, 1),
    last_used_ym VARCHAR(7)
);

CREATE TABLE fact_skill (
    fact_id  BIGINT NOT NULL REFERENCES cv_fact (id) ON DELETE CASCADE,
    skill_id BIGINT NOT NULL REFERENCES skill (id) ON DELETE CASCADE,
    PRIMARY KEY (fact_id, skill_id)
);

CREATE TABLE tag (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE entry_tag (
    entry_id BIGINT NOT NULL REFERENCES cv_entry (id) ON DELETE CASCADE,
    tag_id   BIGINT NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    PRIMARY KEY (entry_id, tag_id)
);

CREATE TABLE fact_tag (
    fact_id BIGINT NOT NULL REFERENCES cv_fact (id) ON DELETE CASCADE,
    tag_id  BIGINT NOT NULL REFERENCES tag (id) ON DELETE CASCADE,
    PRIMARY KEY (fact_id, tag_id)
);

CREATE TABLE style_rule (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_key  TEXT NOT NULL UNIQUE,
    rule_text TEXT NOT NULL,
    enabled   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE search_profile (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt       TEXT NOT NULL,
    profile_json JSONB NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE pipeline_run (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_profile_id BIGINT REFERENCES search_profile (id),
    status            TEXT NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'WAITING_FOR_USER', 'DONE',
                                                       'FAILED', 'CANCELLED')),
    step              TEXT,
    progress          INT NOT NULL DEFAULT 0,
    message           TEXT,
    started_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at       TIMESTAMPTZ
);

CREATE TABLE job (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                   BIGINT REFERENCES pipeline_run (id) ON DELETE SET NULL,
    source                   TEXT NOT NULL,
    source_id                TEXT,
    url                      TEXT,
    apply_url                TEXT,
    title                    TEXT NOT NULL,
    employer                 TEXT,
    client_employer          TEXT,
    location                 TEXT,
    municipality             TEXT,
    published_at             TIMESTAMPTZ,
    deadline                 TIMESTAMPTZ,
    language                 VARCHAR(2),
    employment_type          TEXT,
    description_text         TEXT,
    raw_json                 JSONB,
    asks_for_new_graduates   BOOLEAN NOT NULL DEFAULT FALSE,
    experience_required_text TEXT,
    dedupe_key               TEXT NOT NULL UNIQUE,
    status                   TEXT NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'SHORTLISTED', 'DOCS_READY',
                                                                          'FILLED', 'APPLIED', 'LOGGED',
                                                                          'REJECTED', 'ARCHIVED')),
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_job_run ON job (run_id);

CREATE TABLE job_score (
    job_id                  BIGINT PRIMARY KEY REFERENCES job (id) ON DELETE CASCADE,
    total                   INT NOT NULL,
    tech                    INT NOT NULL,
    experience              INT NOT NULL,
    eligibility             INT NOT NULL,
    fit_text                TEXT,
    gaps_text               TEXT,
    selected_fact_ids_json  JSONB NOT NULL DEFAULT '[]',
    model                   TEXT,
    scored_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE document (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id                BIGINT NOT NULL REFERENCES job (id) ON DELETE CASCADE,
    kind                  TEXT NOT NULL CHECK (kind IN ('CV', 'LETTER')),
    language              VARCHAR(2) NOT NULL,
    content_json          JSONB NOT NULL,
    html                  TEXT,
    pdf_path              TEXT,
    version               INT NOT NULL DEFAULT 1,
    validator_report_json JSONB,
    approved              BOOLEAN NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_document_job ON document (job_id);

CREATE TABLE application_form_snapshot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id       BIGINT NOT NULL REFERENCES job (id) ON DELETE CASCADE,
    url          TEXT,
    fields_json  JSONB NOT NULL,
    actions_json JSONB,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE aktivitet_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id         BIGINT NOT NULL REFERENCES job (id) ON DELETE CASCADE,
    yrkesroll      TEXT,
    employer_label TEXT,
    municipality   TEXT,
    omfattning     TEXT,
    answered_ad    BOOLEAN NOT NULL DEFAULT TRUE,
    applied_date   DATE,
    saved_at       TIMESTAMPTZ,
    result         TEXT,
    message        TEXT
);

-- One row per Claude CLI call (SPEC 5.1), for the usage totals on the Settings page.
CREATE TABLE claude_call (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task                  TEXT NOT NULL,
    model                 TEXT,
    started_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    duration_ms           BIGINT NOT NULL,
    cost_usd              NUMERIC(10, 6),
    input_tokens          BIGINT,
    output_tokens         BIGINT,
    cache_read_tokens     BIGINT,
    cache_creation_tokens BIGINT,
    success               BOOLEAN NOT NULL,
    error_message         TEXT
);
CREATE INDEX idx_claude_call_started ON claude_call (started_at);
