-- Milestone 4: documents, per-job selection and the editable writing rules.

-- Document generation runs on the pipeline executor like a search (CLAUDE.md), so a run has a kind.
ALTER TABLE pipeline_run
    ADD COLUMN kind   TEXT NOT NULL DEFAULT 'SEARCH' CHECK (kind IN ('SEARCH', 'DOCUMENTS')),
    ADD COLUMN job_id BIGINT REFERENCES job (id) ON DELETE CASCADE;

-- Pins and exclusions are the user's choice per job (SPEC 8.1); selection_json is the last result of selectFacts.
ALTER TABLE job
    ADD COLUMN pinned_entry_ids_json   JSONB NOT NULL DEFAULT '[]',
    ADD COLUMN excluded_entry_ids_json JSONB NOT NULL DEFAULT '[]',
    ADD COLUMN selection_json          JSONB;

-- One current document per job and kind; every save or regeneration bumps `version` (SPEC 8.5).
ALTER TABLE document
    ADD CONSTRAINT document_job_kind UNIQUE (job_id, kind),
    ADD COLUMN updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN search_profile_id BIGINT REFERENCES search_profile (id);

-- Case-insensitive; a phrase with " ... " matches the two parts in order within one sentence (SPEC 8.4).
CREATE TABLE banned_phrase (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language VARCHAR(2) NOT NULL CHECK (language IN ('en', 'sv')),
    phrase   TEXT NOT NULL,
    enabled  BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (language, phrase)
);

