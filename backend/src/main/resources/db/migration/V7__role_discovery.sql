-- Discover roles: the role types suggested for a run, which ones the user searched, and which role each ad came from.

CREATE TABLE role_suggestion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id            BIGINT NOT NULL REFERENCES pipeline_run (id) ON DELETE CASCADE,
    title             TEXT NOT NULL,
    category          TEXT NOT NULL CHECK (category IN ('RELATED', 'HYBRID', 'OUTSIDE_TECH', 'CUSTOM')),
    match_score       INT,
    reasoning         TEXT,
    gaps              TEXT,
    selected          BOOLEAN NOT NULL DEFAULT FALSE,
    user_added        BOOLEAN NOT NULL DEFAULT FALSE,
    -- the role-specific search fields Claude proposed; NULL for a role the user added or renamed (built on continue)
    profile_json      JSONB,
    -- the full SearchProfile used to search, rank and tailor documents for this role (immutable, like every profile)
    search_profile_id BIGINT REFERENCES search_profile (id),
    sort_order        INT NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_role_suggestion_run ON role_suggestion (run_id);

-- An ad is scored and tailored once, against the role it fitted best (primary); every role that found it is tagged.
ALTER TABLE run_job ADD COLUMN role_suggestion_id BIGINT REFERENCES role_suggestion (id) ON DELETE SET NULL;

CREATE TABLE run_job_role (
    run_id             BIGINT NOT NULL,
    job_id             BIGINT NOT NULL,
    role_suggestion_id BIGINT NOT NULL REFERENCES role_suggestion (id) ON DELETE CASCADE,
    PRIMARY KEY (run_id, job_id, role_suggestion_id),
    FOREIGN KEY (run_id, job_id) REFERENCES run_job (run_id, job_id) ON DELETE CASCADE
);
