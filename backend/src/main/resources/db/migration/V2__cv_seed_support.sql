-- Milestone 2: columns and tables needed to hold everything in seed/cv_database_seed.json.

ALTER TABLE profile
    ADD COLUMN phone_international TEXT,
    ADD COLUMN work_authorisation  TEXT,
    ADD COLUMN security_vetting    TEXT;

ALTER TABLE cv_entry
    ADD COLUMN title_en TEXT,
    -- note is a to-do or remark for the owner ("Dates missing; add them"). It is internal only and
    -- must never be passed to a prompt or rendered into a CV or letter.
    ADD COLUMN note     TEXT;

-- Honest limitations of the candidate, used when scoring and when writing letters (SPEC 8.1).
CREATE TABLE known_gap (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text       TEXT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0
);

-- Previous answers to screening questions, looked up by normalised question text (SPEC 9.2).
CREATE TABLE answers_memory (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_key TEXT NOT NULL UNIQUE,
    question     TEXT NOT NULL,
    answer       TEXT NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
